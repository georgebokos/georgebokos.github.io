def strip_acc(s_):
    """Χωρίς τόνους. Ο τόνος μετακινείται στον πληθυντικό — «καλαμάρι» αλλά
    «καλαμαράκια» — και η αναζήτηση αστοχούσε σε δεκάδες υλικά."""
    return s_.lower().translate(_ACC)

