def main():
    r = subprocess.run(['node', '-e', JS, os.path.join(ROOT, 'index.html')],
                       capture_output=True, text=True)
    if r.returncode: sys.exit('ΣΦΑΛΜΑ: δεν διαβάστηκε το MEALS\n' + r.stderr)
    M = json.loads(r.stdout)

    res, flags, miss = {}, [], {}
    for rid, m in M.items():
        P, C, F, skipped, notes = analyse(m)
        rr = ratios(P, C, F)
        for s in skipped: miss[s] = miss.get(s, 0) + 1
        if rr is None:
            flags.append((rid, m['n'], 'κανένα υλικό δεν αναγνωρίστηκε')); continue
        # Βαθμονόμηση στις θερμίδες της συνταγής
        cal = m['cal'] or 0
        res[rid] = {'p': round(cal * rr[0] / 100 / 4), 'c': round(cal * rr[1] / 100 / 4),
                    'f': round(cal * rr[2] / 100 / 9), 'r': list(rr)}
        # Σημαίες λογικής
        if rr[2] >= 80 and 'sauces' not in (m['cats'] or []) and 'salads' not in (m['cats'] or []):
            flags.append((rid, m['n'], f'λιπαρά {rr[2]}% — πολύ υψηλό'))
        elif rr[0] >= 70:
            flags.append((rid, m['n'], f'πρωτεΐνη {rr[0]}% — πολύ υψηλό'))
        elif len(skipped) >= 4:
            flags.append((rid, m['n'], f'{len(skipped)} υλικά δεν αναγνωρίστηκαν'))

    tot_lines = sum(len(m['ing']) for m in M.values())
    tot_miss  = sum(miss.values())
    print(f'Συνταγές: {len(M)}  ·  υπολογίστηκαν: {len(res)}')
    print(f'Γραμμές υλικών: {tot_lines}  ·  δεν αναγνωρίστηκαν: {tot_miss} '
          f'({tot_miss*100//tot_lines}%)\n')
    print(f'Συνταγές με σημαία: {len(flags)}')
    for rid, n, why in flags[:40]:
        print(f'   {n[:34]:36} {why}')
    if len(flags) > 40: print(f'   … και άλλες {len(flags)-40}')
    print('\nΑγνοημένα υλικά (κορυφαία 25):')
    for k, v in sorted(miss.items(), key=lambda x: -x[1])[:25]:
        print(f'   {v:>3}×  {k[:60]}')
    if WRITE:
        io.open(OUT, 'w', encoding='utf-8').write(json.dumps(res, ensure_ascii=False, indent=0))
        print(f'\n→ γράφτηκε {OUT}  ({len(res)} συνταγές)')
    else:
        print('\n(δοκιμή — τρέξε με --write για να γραφτεί το JSON)')

if __name__ == '__main__':
    main()
